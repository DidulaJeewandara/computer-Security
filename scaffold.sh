# =============================================================================
#  DeltaForce MFA — repository scaffold
#  Creates the full empty file structure. Run ONCE, from the repo root, by M3,
#  and commit the result before anyone else starts work.
#
#    chmod +x scaffold.sh && ./scaffold.sh
#
#  Every file is created with a single header comment naming its owner (M1-M5)
#  and its purpose, so nobody has to guess where their code goes — and so the
#  first real commit from each member is an edit, not a new file that collides
#  with someone else's new file.
#
#  Safe to re-run: existing files are never overwritten.
# =============================================================================
set -euo pipefail

created=0
skipped=0

# new <path> <comment-line>
new() {
  local path="$1"; shift
  local body="${1:-}"
  if [ -e "$path" ]; then
    skipped=$((skipped + 1))
    return
  fi
  mkdir -p "$(dirname "$path")"
  if [ -n "$body" ]; then
    printf '%s\n' "$body" > "$path"
  else
    : > "$path"
  fi
  created=$((created + 1))
}

